# one-queue version

from collections import deque

class MyStack:

    def __init__(self):
        self.q = deque()

    def push(self, x: int) -> None:
        self.q.append(x)

        # 把最左邊的東西拿出來 `popleft()`，再塞到最右邊 `append()`
        # 就是要把前面 n-1 個舊元素，一個一個搬到新元素的後面
        for _ in range(len(self.q) - 1):
            self.q.append(self.q.popleft())

    def pop(self) -> int:
        return self.q.popleft()

    def top(self) -> int:
        return self.q[0]

    def empty(self) -> bool:
        return not self.q


